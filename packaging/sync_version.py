#!/usr/bin/env python3
"""Write packaging/app_version.iss from app.__version__ (single version source)."""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "app_version.iss"


def main() -> None:
    import sys

    sys.path.insert(0, str(ROOT))
    from app import __version__

    OUT.write_text(
        f'; Auto-generated by packaging/sync_version.py — do not edit by hand.\n'
        f'#define MyAppVersion "{__version__}"\n',
        encoding="utf-8",
    )
    print(f"Wrote {OUT.name} -> {__version__}")


if __name__ == "__main__":
    main()
